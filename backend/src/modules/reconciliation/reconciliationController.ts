import { Request, Response } from 'express';
import mongoose from 'mongoose';
import { ReconciliationEngine } from './reconciliationEngine';
import { ReconciliationRun } from '../../models/ReconciliationRun';
import { MismatchCase } from '../../models/MismatchCase';
import { AuditLog } from '../../models/AuditLog';
import { Notification } from '../../models/Notification';

export class ReconciliationController {
  /**
   * Trigger a new reconciliation run
   */
  static async triggerRun(req: Request, res: Response): Promise<void> {
    const orgId = req.user!.organizationId;
    const userId = new mongoose.Types.ObjectId(req.user!.id);
    const { period, amountTolerance, taxTolerance, dateWindowDays, fuzzyDistance } = req.body;

    try {
      const run = await ReconciliationEngine.run({
        organizationId: orgId,
        initiatedBy: userId,
        period,
        amountTolerance: amountTolerance !== undefined ? Number(amountTolerance) : 1.0,
        taxTolerance: taxTolerance !== undefined ? Number(taxTolerance) : 1.0,
        dateWindowDays: dateWindowDays !== undefined ? Number(dateWindowDays) : 30,
        fuzzyDistance: fuzzyDistance !== undefined ? Number(fuzzyDistance) : 2,
      });

      // Audit Log
      await AuditLog.create({
        organizationId: orgId,
        userId,
        userName: req.user!.name,
        userRole: req.user!.role,
        action: 'EXECUTE_RECONCILIATION_RUN',
        resourceType: 'ReconciliationRun',
        resourceId: run._id.toString(),
        afterState: {
          period: run.period,
          reconciledPercentage: run.reconciledPercentage,
          totalTaxAtRisk: run.totalTaxAtRisk,
        },
        ipAddress: req.ip,
        userAgent: req.headers['user-agent'],
      });

      // Send notification if high tax at risk detected
      if (run.totalTaxAtRisk > 0) {
        await Notification.create({
          organizationId: orgId,
          userId,
          title: `Reconciliation Completed: ₹${run.totalTaxAtRisk.toLocaleString('en-IN')} Tax At Risk`,
          message: `Identified ${run.missingIn2bCount} unfiled supplier invoices and ${run.amountMismatchCount + run.taxMismatchCount} discrepancies.`,
          type: 'HIGH_PRIORITY_MISMATCH',
          entityId: run._id.toString(),
        });
      }

      res.status(201).json({
        success: true,
        message: 'Reconciliation executed successfully',
        run,
      });
    } catch (err: any) {
      res.status(500).json({ success: false, message: `Reconciliation failed: ${err.message}` });
    }
  }

  /**
   * Get all runs for the organization
   */
  static async getRuns(req: Request, res: Response): Promise<void> {
    const runs = await ReconciliationRun.find({ organizationId: req.user!.organizationId })
      .populate('initiatedBy', 'name email')
      .sort({ createdAt: -1 })
      .limit(30);

    res.status(200).json({ success: true, runs });
  }

  /**
   * Get details of a specific run
   */
  static async getRunById(req: Request, res: Response): Promise<void> {
    const run = await ReconciliationRun.findOne({
      _id: req.params.runId,
      organizationId: req.user!.organizationId,
    }).populate('initiatedBy', 'name email');

    if (!run) {
      res.status(404).json({ success: false, message: 'Reconciliation run not found' });
      return;
    }

    res.status(200).json({ success: true, run });
  }

  /**
   * Get cases generated by a specific run (or across the organization)
   */
  static async getCases(req: Request, res: Response): Promise<void> {
    const { runId, matchType, priority, status, search, page = '1', limit = '50' } = req.query;

    const query: any = { organizationId: req.user!.organizationId };
    if (runId) query.runId = runId;
    if (matchType) query.matchType = matchType;
    if (priority) query.priority = priority;
    if (status) query.status = status;

    if (search) {
      query.$or = [
        { supplierGstin: { $regex: search, $options: 'i' } },
        { supplierName: { $regex: search, $options: 'i' } },
        { invoiceNumber: { $regex: search, $options: 'i' } },
      ];
    }

    const pageNum = parseInt(page as string, 10);
    const limitNum = parseInt(limit as string, 10);
    const skip = (pageNum - 1) * limitNum;

    const [cases, total] = await Promise.all([
      MismatchCase.find(query)
        .populate('purchaseInvoiceId')
        .populate('gstr2bInvoiceId')
        .populate('assignedTo', 'name email')
        .sort({ priority: 1, createdAt: -1 }) // CRITICAL/HIGH first
        .skip(skip)
        .limit(limitNum),
      MismatchCase.countDocuments(query),
    ]);

    res.status(200).json({
      success: true,
      total,
      page: pageNum,
      totalPages: Math.ceil(total / limitNum),
      cases,
    });
  }

  /**
   * Main Dashboard aggregate metrics computed directly from real records
   */
  static async getDashboardMetrics(req: Request, res: Response): Promise<void> {
    const orgId = req.user!.organizationId;

    // Latest run
    const latestRun = await ReconciliationRun.findOne({ organizationId: orgId }).sort({ createdAt: -1 });

    // Aggregate counts
    const totalCases = await MismatchCase.countDocuments({ organizationId: orgId });
    const pendingCases = await MismatchCase.countDocuments({ organizationId: orgId, status: 'PENDING_REVIEW' });
    const underReviewCases = await MismatchCase.countDocuments({ organizationId: orgId, status: 'UNDER_REVIEW' });
    const resolvedCases = await MismatchCase.countDocuments({ organizationId: orgId, status: 'RESOLVED' });

    // High priority issues count
    const highPriorityCount = await MismatchCase.countDocuments({
      organizationId: orgId,
      priority: { $in: ['CRITICAL', 'HIGH'] },
      status: { $in: ['PENDING_REVIEW', 'UNDER_REVIEW'] },
    });

    // Breakdown by matchType
    const breakdown = await MismatchCase.aggregate([
      { $match: { organizationId: new mongoose.Types.ObjectId(orgId) } },
      { $group: { _id: '$matchType', count: { $sum: 1 }, totalTaxDiscrepancy: { $sum: '$taxDiscrepancy' } } },
    ]);

    // Priority breakdown
    const priorityBreakdown = await MismatchCase.aggregate([
      { $match: { organizationId: new mongoose.Types.ObjectId(orgId) } },
      { $group: { _id: '$priority', count: { $sum: 1 } } },
    ]);

    res.status(200).json({
      success: true,
      latestRun,
      summary: {
        totalCases,
        pendingCases,
        underReviewCases,
        resolvedCases,
        highPriorityCount,
        breakdown,
        priorityBreakdown,
      },
    });
  }
}
